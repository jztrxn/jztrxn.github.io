#!/usr/bin/env python3
"""
Update the portfolio website from the Resumes folder.

1. Copies the newest dated CV PDF (e.g. 20261103_CV_Joseph_Tran.pdf) to
   assets/Joseph_Tran_CV.pdf, which the site's "Download CV" button serves.
2. Rebuilds the "Published" list on publications.html from the Zotero
   auto-exported "Personal Publications.bib", newest first.
3. Commits and pushes the changes to GitHub (skip with --no-push).

Usage:  python3 scripts/update_website.py [--dry-run] [--no-push]
Only the Python standard library is used.
"""
import argparse, filecmp, html, re, shutil, subprocess, sys
from datetime import date
from pathlib import Path

# ---------------- Settings ----------------
RESUMES_DIR = Path.home() / "Library/CloudStorage/Dropbox/Jo Tran/04_Shared Resources/Resumes"
BIB_FILE    = RESUMES_DIR / "Personal Publications.bib"
CV_PATTERN  = re.compile(r"^(\d{8})_CV.*\.pdf$", re.IGNORECASE)   # dated CVs only

SITE_DIR    = Path(__file__).resolve().parent.parent
CV_TARGET   = SITE_DIR / "assets" / "Joseph_Tran_CV.pdf"
PUBS_PAGE   = SITE_DIR / "publications.html"

MY_FAMILY, MY_GIVEN = "Tran", "Joseph"     # name to bold
MAX_AUTHORS = 6                            # longer lists become "first 3 et al."
START = "<!-- AUTO-PUBLICATIONS:START (generated by scripts/update_website.py; edit Zotero, not this list) -->"
END   = "<!-- AUTO-PUBLICATIONS:END -->"
MONTHS = ["", "January", "February", "March", "April", "May", "June", "July",
          "August", "September", "October", "November", "December"]

# ---------------- BibTeX / BibLaTeX parsing ----------------
def parse_bib(text):
    entries, i = [], 0
    while True:
        at = text.find("@", i)
        if at < 0:
            break
        m = re.match(r"@(\w+)\s*\{", text[at:])
        if not m:
            i = at + 1
            continue
        etype = m.group(1).lower()
        j = at + m.end()
        depth, k = 1, j
        while k < len(text) and depth:
            if text[k] == "{": depth += 1
            elif text[k] == "}": depth -= 1
            k += 1
        body = text[j:k - 1]
        i = k
        if etype in ("comment", "string", "preamble"):
            continue
        key, _, rest = body.partition(",")
        entries.append({"_type": etype, "_key": key.strip(), **parse_fields(rest)})
    return entries

def parse_fields(s):
    fields, i, n = {}, 0, len(s)
    while i < n:
        m = re.compile(r"\s*([\w\-]+)\s*=\s*").match(s, i)
        if not m:
            break
        name, i = m.group(1).lower(), m.end()
        if i < n and s[i] == "{":
            depth, j = 1, i + 1
            while j < n and depth:
                if s[j] == "{": depth += 1
                elif s[j] == "}": depth -= 1
                j += 1
            val, i = s[i + 1:j - 1], j
        elif i < n and s[i] == '"':
            j = s.find('"', i + 1)
            val, i = s[i + 1:j], j + 1
        else:
            j = i
            while j < n and s[j] not in ",\n":
                j += 1
            val, i = s[i:j].strip(), j
        fields[name] = val
        while i < n and s[i] in " ,\n\r\t":
            i += 1
    return fields

def clean(s):
    """LaTeX field text -> plain text."""
    if not s:
        return ""
    s = s.replace("{$<$}", "<").replace("{$>$}", ">").replace("$<$", "<").replace("$>$", ">")
    s = re.sub(r"\\textit\{([^{}]*)\}|\\emph\{([^{}]*)\}", lambda m: m.group(1) or m.group(2), s)
    for a, b in [(r"\&", "&"), (r"\_", "_"), (r"\%", "%"), (r"\$", "$"), (r"\#", "#"),
                 ("---", "\u2014"), ("--", "\u2013"), ("~", "\u00a0")]:
        s = s.replace(a, b)
    s = s.replace("{", "").replace("}", "")
    return re.sub(r"\s+", " ", s).strip()

# ---------------- Formatting ----------------
def fmt_author(name):
    name = clean(name)
    if "," in name:
        family, given = [p.strip() for p in name.split(",", 1)]
    else:
        parts = name.split()
        family, given = parts[-1], " ".join(parts[:-1])
    initials = "".join(p[0] for p in re.split(r"[\s\-.]+", given) if p)
    label = html.escape(f"{family} {initials}".strip())
    is_me = family == MY_FAMILY and given.split()[:1] == [MY_GIVEN]
    return f"<strong>{label}</strong>" if is_me else label

def fmt_authors(raw):
    names = [a for a in re.split(r"\s+and\s+", raw or "") if a.strip()]
    shown = [fmt_author(a) for a in names]
    if len(shown) > MAX_AUTHORS:
        mine = next((x for x in shown if x.startswith("<strong>")), None)
        first = shown[:3]
        if mine and mine not in first:
            first.append(mine)
        return ", ".join(first) + " et al."
    return ", ".join(shown)

def entry_date(e):
    raw = e.get("date", "")
    m = re.match(r"(\d{4})(?:-(\d{1,2}))?(?:-(\d{1,2}))?", raw)
    if m:
        return tuple(int(x) if x else 0 for x in m.groups())
    y = int(e["year"]) if e.get("year", "").isdigit() else 0
    mon = e.get("month", "")
    mon = int(mon) if mon.isdigit() else (MONTHS.index(mon.capitalize()) if mon.capitalize() in MONTHS else 0)
    return (y, mon, 0)

def fmt_entry(e):
    y, m, _ = entry_date(e)
    title = html.escape(clean(e.get("title", "Untitled")))
    venue_bits = []
    journal = clean(e.get("journaltitle") or e.get("journal") or e.get("booktitle") or "")
    if journal:
        venue_bits.append(f"<em>{html.escape(journal)}</em>")
    vol = clean(e.get("volume", ""))
    issue = clean(e.get("number", "") or e.get("issue", "")).replace("Suppl_", "Suppl ").replace("Suppl_", "Suppl ")
    vi = (vol + (f" ({issue})" if issue else "")).strip()
    pages = clean(e.get("pages", ""))
    tail = ", ".join(x for x in [html.escape(vi), html.escape(pages) if pages else ""] if x)
    when = " ".join(x for x in [MONTHS[m] if m else "", str(y) if y else ""] if x)
    venue = " ".join(venue_bits + ([tail] if tail else []))
    venue = ", ".join(x for x in [venue, when] if x)
    line = fmt_authors(e.get("author", ""))
    if venue:
        line += f". {venue}."
    link = ""
    doi, url = clean(e.get("doi", "")), clean(e.get("url", ""))
    if doi or url:
        href = f"https://doi.org/{doi}" if doi else url
        label = f"DOI: {html.escape(doi)}" if doi else "View publication"
        link = (f'\n<a class="font-mono text-[10px] uppercase tracking-widest text-primary inline-flex items-center gap-2 hover:opacity-70" '
                f'href="{html.escape(href, quote=True)}" target="_blank" rel="noopener">{label} '
                f'<span class="material-symbols-outlined text-[14px]">open_in_new</span></a>')
    return (
        '<div class="flex gap-4 md:gap-8 py-6 border-b border-outline-variant/30 hover:bg-surface-container-low transition-colors px-2 md:px-4">\n'
        f'<span class="w-12 md:w-16 shrink-0 font-mono text-base md:text-lg font-bold text-primary">{y or ""}</span>\n'
        '<div class="flex-grow">\n'
        f'<h3 class="text-lg md:text-xl font-headline font-bold leading-snug mb-1">{title}</h3>\n'
        f'<p class="text-sm text-on-surface-variant mb-2">{line}</p>{link}\n'
        '</div>\n</div>'
    )

def build_list(entries):
    entries = sorted(entries, key=lambda e: (entry_date(e), clean(e.get("title", ""))), reverse=True)
    return "\n".join(fmt_entry(e) for e in entries)

# ---------------- Page update ----------------
def update_publications(dry):
    if not BIB_FILE.exists():
        sys.exit(f"Can't find the Zotero file: {BIB_FILE}")
    entries = parse_bib(BIB_FILE.read_text(encoding="utf-8"))
    page = PUBS_PAGE.read_text(encoding="utf-8")
    if START not in page:
        # First run: wrap the existing "Published" list in markers.
        m = re.search(r'(<h2[^>]*>Published</h2>\s*<div class="border-t[^"]*">)(.*?)(</div>\s*</section>)', page, re.S)
        if not m:
            sys.exit("Couldn't find the Published section in publications.html.")
        page = page[:m.end(1)] + f"\n{START}\n{END}\n" + page[m.start(3):]
    new_block = f"{START}\n{build_list(entries)}\n{END}"
    new_page = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: new_block, page, flags=re.S)
    changed = new_page != PUBS_PAGE.read_text(encoding="utf-8")
    if changed and not dry:
        PUBS_PAGE.write_text(new_page, encoding="utf-8")
    print(f"Publications: {len(entries)} in Zotero file -> " + ("page updated" if changed else "page already up to date"))
    for e in sorted(entries, key=entry_date, reverse=True):
        print(f"   {entry_date(e)[0]}  {clean(e.get('title',''))[:90]}")
    return changed

def update_cv(dry):
    cvs = sorted((p for p in RESUMES_DIR.iterdir() if CV_PATTERN.match(p.name)),
                 key=lambda p: CV_PATTERN.match(p.name).group(1))
    if not cvs:
        print("CV: no dated CV PDF (YYYYMMDD_CV_....pdf) found in the Resumes folder; skipped.")
        return False
    newest = cvs[-1]
    if CV_TARGET.exists() and filecmp.cmp(newest, CV_TARGET, shallow=False):
        print(f"CV: website already has the newest CV ({newest.name})")
        return False
    if not dry:
        shutil.copyfile(newest, CV_TARGET)
    print(f"CV: copied {newest.name} -> assets/{CV_TARGET.name}")
    return True

def git(*args):
    return subprocess.run(["git", *args], cwd=SITE_DIR, text=True, capture_output=True)

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dry-run", action="store_true", help="show what would change, write nothing")
    ap.add_argument("--no-push", action="store_true", help="update files but don't commit or push")
    a = ap.parse_args()
    if not RESUMES_DIR.exists():
        sys.exit(f"Can't find the Resumes folder: {RESUMES_DIR}")
    cv_changed = update_cv(a.dry_run)
    pubs_changed = update_publications(a.dry_run)
    if a.dry_run:
        print("\nDry run: nothing was written.")
        return
    if not (cv_changed or pubs_changed):
        print("\nEverything is already up to date. Nothing to publish.")
        return
    if a.no_push:
        print("\nFiles updated. Not committed (--no-push).")
        return
    files = [str(p.relative_to(SITE_DIR)) for p, c in [(CV_TARGET, cv_changed), (PUBS_PAGE, pubs_changed)] if c]
    git("add", *files)
    what = " and ".join(x for x, c in [("CV", cv_changed), ("publications", pubs_changed)] if c)
    r = git("commit", "-m", f"Update {what} ({date.today().isoformat()})")
    if r.returncode != 0:
        sys.exit("git commit failed:\n" + r.stdout + r.stderr)
    r = git("push")
    if r.returncode != 0:
        sys.exit("Committed, but the push to GitHub failed:\n" + r.stderr + "\nTry pushing from GitHub Desktop or `git push`.")
    print(f"\nPublished to GitHub. The live site updates in a minute or two: https://jztrxn.github.io")

if __name__ == "__main__":
    main()
